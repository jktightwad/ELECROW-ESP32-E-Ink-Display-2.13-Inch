#!/usr/bin/env python3
"""Converts the TrueType fonts in tools/fonts/ into Adafruit GFX fonts
(include/fonts/*.h) for the e-paper display.

Glyphs are rendered with Pillow at the given pixel size and thresholded to
1 bit (no anti-aliasing), the same way the panel shows them.

Text fonts cover printable ASCII; '~' is replaced by the degree sign, so draw
"72~" to get "72°". Icon fonts map Weather Icons glyphs onto consecutive
characters starting at '!' (see ICONS and include/fonts/weather_icons.h).

Run from the repository root:  python3 tools/make_fonts.py
Needs: pip install pillow
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "fonts"
OUT = ROOT / "include" / "fonts"

# name, ttf, pixel size
TEXT_FONTS = [
    ("Barlow_SB13", "Barlow-SemiBold.ttf", 13),
    ("Barlow_SB14", "Barlow-SemiBold.ttf", 14),
    ("Barlow_M12", "Barlow-Medium.ttf", 12),
    ("BarlowCond_SB50", "BarlowCondensed-SemiBold.ttf", 50),
]

# Weather Icons glyphs used (name -> codepoint, from the project's CSS).
ICONS = [
    ("NA", 0xF07B), ("DAY_SUNNY", 0xF00D), ("NIGHT_CLEAR", 0xF02E),
    ("DAY_SUNNY_OVERCAST", 0xF00C), ("DAY_CLOUDY", 0xF002), ("NIGHT_CLOUDY", 0xF086),
    ("CLOUDY", 0xF013), ("FOG", 0xF014), ("SPRINKLE", 0xF01C),
    ("DAY_RAIN", 0xF008), ("NIGHT_RAIN", 0xF028), ("RAIN", 0xF019), ("RAIN_MIX", 0xF017),
    ("DAY_SNOW", 0xF00A), ("NIGHT_SNOW", 0xF02A), ("SNOW", 0xF01B),
    ("DAY_SHOWERS", 0xF009), ("NIGHT_SHOWERS", 0xF029),
    ("DAY_THUNDER", 0xF010), ("NIGHT_THUNDER", 0xF02D), ("THUNDER", 0xF01E),
    ("HUMIDITY", 0xF07A), ("WIND", 0xF050), ("RAINDROP", 0xF078),
    ("SUNRISE", 0xF051), ("SUNSET", 0xF052),
]
# name, pixel size; the big icon is fitted into a box by the drawing code.
ICON_FONTS = [("WeatherIcons_L", 44), ("WeatherIcons_S", 15), ("WeatherIcons_M", 18)]

FIRST = 0x20


def render_glyph(font, ch):
    """Returns (bitmap rows as lists of 0/1, width, height, x_offset, y_offset, x_advance)."""
    ascent, _ = font.getmetrics()
    advance = round(font.getlength(ch))
    l, t, r, b = font.getbbox(ch)            # relative to the top of the ascent line
    w, h = max(r - l, 0), max(b - t, 0)
    if w == 0 or h == 0:
        return [], 0, 0, 0, 0, advance
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255)
    px = img.load()
    rows = [[1 if px[x, y] >= 128 else 0 for x in range(w)] for y in range(h)]
    # trim empty rows/columns left by thresholding
    while rows and not any(rows[0]): rows.pop(0); t += 1
    while rows and not any(rows[-1]): rows.pop()
    if not rows:
        return [], 0, 0, 0, 0, advance
    cols = list(zip(*rows))
    left = next(i for i, c in enumerate(cols) if any(c))
    right = len(cols) - next(i for i, c in enumerate(reversed(cols)) if any(c))
    rows = [row[left:right] for row in rows]
    l += left
    return rows, len(rows[0]), len(rows), l, t - ascent, advance


def write_font(name, font, chars, comment):
    bits, glyphs = [], []
    for ch in chars:
        rows, w, h, xo, yo, adv = render_glyph(font, ch)
        glyphs.append((len(bits) // 8, w, h, adv, xo, yo))
        flat = [v for row in rows for v in row]
        flat += [0] * (-len(flat) % 8)
        bits.extend(flat)
    data = [int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8)]
    ascent, descent = font.getmetrics()
    lines = [f"// {comment}", "// Generated by tools/make_fonts.py - do not edit.", "#pragma once",
             "#include <Adafruit_GFX.h>", "",
             f"const uint8_t {name}Bitmaps[] PROGMEM = {{"]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{v:02X}" for v in data[i:i + 16]) + ",")
    lines += ["};", "", f"const GFXglyph {name}Glyphs[] PROGMEM = {{"]
    for ch, g in zip(chars, glyphs):
        label = "'~' (degree)" if ch == "°" else repr(ch)
        lines.append("  {{{:5d}, {:3d}, {:3d}, {:3d}, {:4d}, {:4d}}},  // {}".format(*g, label))
    lines += ["};", "",
              f"const GFXfont {name} PROGMEM = {{(uint8_t*){name}Bitmaps, (GFXglyph*){name}Glyphs, "
              f"0x{FIRST:02X}, 0x{FIRST + len(chars) - 1:02X}, {ascent + descent}}};", ""]
    (OUT / f"{name}.h").write_text("\n".join(lines))
    print(f"{name}: {len(chars)} glyphs, {len(data)} bitmap bytes")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    ascii_chars = [chr(c) for c in range(FIRST, 0x7F)]
    ascii_chars[ord("~") - FIRST] = "°"
    for name, ttf, size in TEXT_FONTS:
        write_font(name, ImageFont.truetype(str(SRC / ttf), size), ascii_chars,
                   f"{ttf} at {size}px (SIL OFL 1.1, see tools/fonts/OFL-Barlow.txt)")
    icon_chars = [" "] + [chr(cp) for _, cp in ICONS]
    for name, size in ICON_FONTS:
        write_font(name, ImageFont.truetype(str(SRC / "weathericons.ttf"), size), icon_chars,
                   f"Weather Icons at {size}px (SIL OFL 1.1, see tools/fonts/OFL-WeatherIcons.txt)")
    enum = ["// Generated by tools/make_fonts.py - do not edit.", "#pragma once", "",
            "// Characters for the WeatherIcons_* fonts.", "namespace WI {"]
    for i, (n, cp) in enumerate(ICONS):
        enum.append(f"  const char {n} = 0x{FIRST + 1 + i:02X};  // U+{cp:04X}")
    enum += ["}", ""]
    (OUT / "weather_icons.h").write_text("\n".join(enum))
    print("weather_icons.h written")


if __name__ == "__main__":
    main()
