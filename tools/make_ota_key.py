#!/usr/bin/env python3
"""Creates the key pair used to sign firmware updates. Run ONCE, on your own PC.

  python tools/make_ota_key.py

It prints the PRIVATE key (64 hex characters): store it as a GitHub Actions
secret named OTA_SIGNING_KEY (repository Settings > Secrets and variables >
Actions > New repository secret), then delete it from your screen/clipboard.
Never commit it or paste it anywhere else; anyone holding it can sign
firmware that your displays will accept.

It writes the matching PUBLIC key to include/ota_public_key.h, which is
built into the firmware and is safe to commit.

Needs only Python 3 (no extra packages). Key: ECDSA P-256.
"""
import secrets
from pathlib import Path

# NIST P-256 curve parameters
P = 0xFFFFFFFF00000001000000000000000000000000FFFFFFFFFFFFFFFFFFFFFFFF
A = P - 3
N = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551
G = (0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296,
     0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5)


def add(p1, p2):
    if p1 is None: return p2
    if p2 is None: return p1
    (x1, y1), (x2, y2) = p1, p2
    if x1 == x2 and (y1 + y2) % P == 0:
        return None
    if p1 == p2:
        m = (3 * x1 * x1 + A) * pow(2 * y1, -1, P) % P
    else:
        m = (y2 - y1) * pow(x2 - x1, -1, P) % P
    x3 = (m * m - x1 - x2) % P
    return (x3, (m * (x1 - x3) - y1) % P)


def mul(k, point):
    result = None
    while k:
        if k & 1:
            result = add(result, point)
        point = add(point, point)
        k >>= 1
    return result


def public_key_der(d):
    x, y = mul(d, G)
    # SubjectPublicKeyInfo for an uncompressed P-256 point
    prefix = bytes.fromhex("3059301306072a8648ce3d020106082a8648ce3d030107034200")
    return prefix + b"\x04" + x.to_bytes(32, "big") + y.to_bytes(32, "big")


def main():
    out = Path(__file__).resolve().parent.parent / "include" / "ota_public_key.h"
    if out.exists() and "replace-me" not in out.read_text():
        answer = input(f"{out.name} already holds a key. Replace it? Devices with the old key "
                       "will reject updates signed with the new one. [y/N] ")
        if answer.strip().lower() != "y":
            print("Nothing changed.")
            return
    d = secrets.randbelow(N - 1) + 1
    der = public_key_der(d)
    body = ",\n".join("  " + ", ".join(f"0x{b:02X}" for b in der[i:i + 16]) for i in range(0, len(der), 16))
    out.write_text(
        "// Public key for verifying firmware updates (ECDSA P-256, DER SubjectPublicKeyInfo).\n"
        "// Generated by tools/make_ota_key.py. Safe to commit: it can only check signatures.\n"
        "#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n"
        f"static const uint8_t OTA_PUBLIC_KEY_DER[] = {{\n{body}\n}};\n"
        "static const size_t OTA_PUBLIC_KEY_DER_LEN = sizeof(OTA_PUBLIC_KEY_DER);\n")
    print(f"Public key written to {out}")
    print()
    print("PRIVATE KEY - store as GitHub secret OTA_SIGNING_KEY, then clear it from your screen:")
    print(f"{d:064x}")


if __name__ == "__main__":
    main()
